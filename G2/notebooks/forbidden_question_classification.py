from lime.lime_text import LimeTextExplainer
import numpy as np
import torch

# Optimized predict_proba function using CPU
def predict_proba(texts):
    # Move model to CPU
    device_cpu = torch.device("cpu")
    model.to(device_cpu)
    model.eval()

    probs = []
    for text in texts:
        # Tokenize input text
        encodings = tokenizer([text], padding='max_length', truncation=True, max_length=128, return_tensors='pt')
        encodings = {key: val.to(device_cpu) for key, val in encodings.items()}

        # Get prediction probabilities
        with torch.no_grad():
            logits = model(**encodings).logits
            prob = torch.softmax(logits, dim=1).cpu().numpy()
        probs.append(prob)

    # Return probabilities as a NumPy array
    return np.vstack(probs)

